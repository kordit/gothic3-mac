#!/usr/bin/env python3
"""Render games/<id>/game.toml into game_config.h and game_config.cmake.

    tools/gen_game_config.py --game-dir /abs/path/to/<game> --header OUT.h --cmake OUT.cmake

The header is what runtime/, dx/ and host/ include for every game-specific
value; the cmake fragment names the app and the image base for the build."""

import json
import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import game_config  # noqa: E402
import launcher_config  # noqa: E402

STRINGS = (("id", "RECOMP_GAME_ID"), ("name", "RECOMP_GAME_NAME"), ("app_name", "RECOMP_APP_NAME"),
           ("data_dir_name", "RECOMP_DATA_DIR_NAME"),
           ("bundle_id", "RECOMP_BUNDLE_ID"), ("executable", "RECOMP_EXECUTABLE"),
           ("sha256", "RECOMP_EXE_SHA256"), ("guest_root", "RECOMP_GUEST_ROOT"))
ADDRESSES = (("image_base", "RECOMP_IMAGE_BASE"), ("entry_point", "RECOMP_ENTRY_POINT"),
             ("heap_base", "RECOMP_HEAP_BASE"), ("heap_extra_base", "RECOMP_HEAP_EXTRA_BASE"),
             ("heap_extra_size", "RECOMP_HEAP_EXTRA_SIZE"))


def c_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def c_hex(value):
    return "0x%08xu" % value


def c_string_list(values):
    """A brace initializer of C strings ending in a null pointer."""
    return "{" + "".join(c_string(v) + ", " for v in values) + "0}"


def render_header(cfg):
    game = cfg["game"]
    lines = ["/* generated by tools/gen_game_config.py from %s -- do not edit */" % cfg["source"],
             "#pragma once"]
    for key, macro in STRINGS:
        lines.append("#define %s %s" % (macro, c_string(game[key])))
    for key, macro in ADDRESSES:
        lines.append("#define %s %s" % (macro, c_hex(game[key])))
    for field, value in zip(("MAJOR", "MINOR", "BUILD", "PLATFORM"),
                            game_config.windows_version(game["windows_version"])):
        lines.append("#define RECOMP_WINDOWS_%s %du" % (field, value))
    lines.append("#define RECOMP_CPUID_FEATURES_EDX 0x%08xu" % game_config.cpu_features_edx(game["cpu_features"]))
    lines.append("#define RECOMP_CPUID_BRAND_INDEX 0x%02xu" % game["cpu_brand_index"])
    lines.append("#define RECOMP_QPC_US %d" % game["qpc_us"])
    lines.append("#define RECOMP_PHYSICAL_MEMORY_MB %du" % game["physical_memory_mb"])
    lines.append("#define RECOMP_FREE_THREADS_DEFAULT %s" % json.dumps(game.get("free_threads", "")))
    lines.append("#define RECOMP_VIRTUAL_MEMORY_MB %du" % game.get("virtual_memory_mb", 2047))
    lines.append("#define RECOMP_D3D9_PRESENT_ASYNC_DEFAULT %d" % game.get("present_async", 0))
    lines.append("#define RECOMP_D3D9_QUERY_NOSYNC_DEFAULT %d" % int(game.get("query_nosync", False)))
    lines.append("#define RECOMP_D3D9_SCALE_MAX_DEFAULT %.3ff" % float(game.get("render_scale_max", 8.0)))
    if game.get("frame_cap"):
        lines.append("#define RECOMP_GAME_FRAME_CAP_ADDR %s" % c_hex(game["frame_cap"]))
    # The display adapter D3D9 names (GetAdapterIdentifier); games pick their detail by its ids ([game] adapter).
    lines.append("#define RECOMP_ADAPTER_VENDOR 0x%04xu" % game["adapter"]["vendor"])
    lines.append("#define RECOMP_ADAPTER_DEVICE 0x%04xu" % game["adapter"]["device"])
    lines.append("#define RECOMP_ADAPTER_NAME %s" % c_string(game["adapter"]["name"]))
    lines.append("#define RECOMP_ADAPTER_MODE_LIST %d" % (game["adapter"]["modes"] == "list"))
    # Absolute: the developer's game lives beside game.toml, not under the kit.
    lines.append("#define RECOMP_DEVELOPER_EXE %s" % c_string(cfg["developer_exe_path"].as_posix()))
    lines.append("#define RECOMP_DEVELOPER_GAME_DIR %s" % c_string(cfg["developer_exe_path"].parent.as_posix()))
    lines.append("#define RECOMP_GAME_DIR %s" % c_string(Path(cfg["dir"]).resolve().as_posix()))
    lines.append("#define RECOMP_KIT_DIR %s" % c_string(Path(__file__).resolve().parents[1].as_posix()))
    # The on-screen controls a fresh profile starts with, and how the pad maps
    # onto the keyboard/mouse or a real controller (games/stub/game.toml [controls]).
    controls = cfg["controls"]
    lines.append("#define RECOMP_CONTROLS_DEFAULT_LAYOUT %s" % c_string(controls["default_layout"]))
    lines.append("#define RECOMP_CONTROLS_PAD %d" % ("off", "mapped", "native").index(controls["pad"]))
    lines.append("#define RECOMP_CONTROLS_MAPPED %s" % c_string(
        ";".join("%s=%s" % (k, controls["mapped"][k]) for k in sorted(controls["mapped"]))))
    native = controls["native"]
    lines.append("#define RECOMP_CONTROLS_XINPUT %d" % int(native["xinput"]))
    lines.append("#define RECOMP_CONTROLS_DINPUT %d" % int(native["dinput"]))
    lines.append("#define RECOMP_CONTROLS_NATIVE_AXES %s" % c_string(",".join(native["axes"])))
    lines.append("#define RECOMP_CONTROLS_NATIVE_BUTTONS %s" % c_string(",".join(native["buttons"])))
    lines.append("#define RECOMP_GUEST_SIZE %s" % c_hex(game["guest_size"]))
    lines.append("#define RECOMP_RESUMABLE_STACKS %d" %
                 int(cfg["translate"].get("resumable_stacks", False)))
    lines.append("#define RECOMP_GAME_STORE_HOOKS %d" % int(cfg["translate"].get("store_hooks", True)))
    lines.append("#define RECOMP_CD_AUDIO_TRACKS %s" % c_string_list(cfg.get("media", {}).get("cd_tracks", [])))
    # Auxiliary modules the loader maps beside the image: {name, developer path, sha256, base, size}.
    lines.append("#define RECOMP_AUX_MODULE_COUNT %d" % len(cfg["aux_modules"]))
    lines.append("#define RECOMP_AUX_MODULES {%s}" % ", ".join(
        '{%s, %s, %s, %s, 0x%08xu}' % (c_string(m["name"]), c_string(m["path"].as_posix()), c_string(m["sha256"]),
                                        c_hex(m["base"]), m["size"])
        for m in cfg["aux_modules"]) if cfg["aux_modules"] else "#define RECOMP_AUX_MODULES {{0, 0, 0, 0u, 0u}}")
    # Imports a module takes from another module's code: {importer base, dll, name, address}.
    forwards = [(m["base"], dll, name, to) for m in cfg["aux_modules"] for dll, name, to in m["import_forwards"]]
    lines.append("#define RECOMP_IMPORT_FORWARD_COUNT %d" % len(forwards))
    lines.append("#define RECOMP_IMPORT_FORWARDS {%s}" % ", ".join(
        "{%s, %s, %s, %s}" % (c_hex(base), c_string(dll), c_string(name), c_hex(to))
        for base, dll, name, to in forwards) if forwards else "#define RECOMP_IMPORT_FORWARDS {{0u, 0, 0, 0u}}")
    # Data values the loader replaces in a mapped module: {address, bytes (4 or 8), expected, new}.
    patches = [d for m in cfg["aux_modules"] for d in m["data"]]
    lines.append("#define RECOMP_DATA_PATCH_COUNT %d" % len(patches))
    lines.append("#define RECOMP_DATA_PATCHES {%s}" % ", ".join(
        "{%s, %du, 0x%016xull, 0x%016xull}" % (c_hex(at), n, was, now) for at, n, was, now in patches)
        if patches else "#define RECOMP_DATA_PATCHES {{0u, 0u, 0ull, 0ull}}")
    # The mod runtime's built-in game integrations (animation clock, native
    # options menu, settings persistence, sprite view) were written against
    # Populous and hook its routines by address. Another game turns them off.
    builtin = cfg.get("mods", {}).get("builtin", "populous")
    if builtin not in ("populous", "none"):
        raise ValueError('[mods] builtin must be "populous" or "none", not %r' % builtin)
    lines.append("#define RECOMP_MODS_BUILTIN_POPULOUS %d" % (1 if builtin == "populous" else 0))
    # One bit per settings-page row, in game_config.SETTINGS_ROWS order.
    mask = sum(1 << i for i, row in enumerate(game_config.SETTINGS_ROWS) if row in cfg["settings"]["rows"])
    lines.append("#define RECOMP_SETTINGS_ROWS 0x%03xu" % mask)
    lines.append("#define RECOMP_SETTINGS_FILTERING_DEFAULT %d" % cfg["settings"]["filtering_default"])
    lines.append("#define RECOMP_SETTINGS_FILTERING_KEY %s" % c_string(cfg["settings"]["filtering_key"]))
    lines.append("#define RECOMP_SETTINGS_PAGE_TABS %d" % (cfg["settings"]["page"] == "tabs"))
    lines.append("#define RECOMP_SETTINGS_CORE_MOD %s" % c_string(cfg["settings"]["core_mod"]))
    # The launcher's data: what to call the game, where to get it, where an
    # install may be, and what an import copies (host/launcher/).
    launcher = cfg["launcher"]
    lines.append("#define RECOMP_LAUNCHER_TITLE %s" % c_string(launcher["title"]))
    lines.append("#define RECOMP_LAUNCHER_STORE_URL %s" % c_string(launcher["store"]))
    lines.append("#define RECOMP_RELEASES_REPO %s" % c_string(launcher["releases_repo"]))
    lines.append("#define RECOMP_SETUP_LOG %s" % c_string(launcher["setup_log"]))
    lines.append("#define RECOMP_LAUNCHER_INSTALL_NAMES %s" % c_string_list(launcher["install_names"]))
    lines.append("#define RECOMP_LAUNCHER_GOG_IDS %s" % c_string_list(launcher["gog_ids"]))
    lines.append("#define RECOMP_LAUNCHER_STEAM_IDS %s" % c_string_list(launcher["steam_ids"]))
    lines.append("#define RECOMP_LAUNCHER_NATIVE_DLLS %s" % c_string_list(launcher["native_dlls"]))
    lines.append("#define RECOMP_LAUNCHER_NATIVE_MOD_DLLS %s" % c_string_list(launcher["native_mod_dlls"]))
    lines.append("#define RECOMP_LAUNCHER_MIN_FREE_MB %du" % launcher["min_free_mb"])
    lines.append("#define RECOMP_LAUNCHER_SEFARIS_DIR %s" % c_string(launcher["sefaris_dir"]))
    lines.append("#define RECOMP_LAUNCHER_LANGUAGE %s" % c_string(launcher["language"]))
    lines.append("#define RECOMP_LAUNCHER_BANNER %s" % c_string(launcher["banner"]))
    lines.append("#define RECOMP_LAUNCHER_SUBTITLE %s" % c_string(launcher["subtitle"]))
    lines.append("#define RECOMP_LAUNCHER_FONT_DISPLAY %s" % c_string_list(launcher["font_display"]))
    lines.append("#define RECOMP_LAUNCHER_FONT_BODY %s" % c_string_list(launcher["font_body"]))
    lines.append("#define RECOMP_LAUNCHER_FONT_STRONG %s" % c_string_list(launcher["font_strong"]))
    lines.append("#define RECOMP_LAUNCHER_BACKDROP_VIDEO %s" % c_string(launcher["backdrop_video"]))
    lines.append("#define RECOMP_LAUNCHER_BACKDROP_SECONDS %r" % float(launcher["backdrop_seconds"]))
    # The game from the player's Steam account (D-037): {depot, manifest, branch, filelist lines, MB, label}.
    steam = launcher_config.load_steam(launcher, cfg["source"])
    lines.append("#define RECOMP_LAUNCHER_STEAM_TOOL %s" % c_string(steam["tool"]))
    lines.append("#define RECOMP_LAUNCHER_STEAM_APP %du" % steam["app"])
    lines.append("#define RECOMP_LAUNCHER_STEAM_DEPOT_COUNT %d" % len(steam["depots"]))
    lines.append("#define RECOMP_LAUNCHER_STEAM_DEPOTS {%s}" % (", ".join(
        "{%du, %s, %s, %s, %du, %s, %s, %s}" % (d["id"], c_string(d["manifest"]), c_string(d["branch"]),
                                                c_string("\n".join(d["files"])), d["mb"], c_string(d["label"]),
                                                c_string("\n".join(d["ini_on"])), c_string("\n".join(d["ini_off"])))
        for d in steam["depots"]) or "{0u, 0, 0, 0, 0u, 0, 0, 0}"))
    lines.append("#define RECOMP_LAUNCHER_STEAM_INI %s" % c_string("\n".join(steam["ini"])))
    lines.append("#define RECOMP_LAUNCHER_ALWAYS %d" % int(launcher_config.load_always(launcher, cfg["source"])))
    mods_url = launcher.get("mods_url", "")
    if not isinstance(mods_url, str) or (mods_url and not mods_url.startswith("https://")):
        raise ValueError("%s: [launcher] mods_url must be an https:// address" % cfg["source"])
    lines.append("#define RECOMP_LAUNCHER_MODS_URL %s" % c_string(mods_url))
    lines.append("#define RECOMP_LAUNCHER_DEFAULT_MODS %s" % c_string(
        "\n".join(launcher_config.load_default_mods(launcher, cfg["source"]))))
    lines.append("#define RECOMP_LAUNCHER_PROFILE_SEED %s" % c_string(
        "\n".join(launcher_config.load_profile_seed(launcher, cfg["source"]))))
    # Modules the launcher makes from the player's files: {name, path beside the executable, from,
    # from_sha256, prepare, base, sha256 of the result}.
    tables = cfg.get("modules", {}).get("aux", {})
    staged = [(m, launcher_config.aux_stage(tables[m["key"]], cfg["source"], m["key"])) for m in cfg["aux_modules"]]
    staged = [(m, st) for m, st in staged if st]
    exe_dir = cfg["developer_exe_path"].parent
    def beside(m):
        return m["path"].relative_to(exe_dir).as_posix() if m["path"].is_relative_to(exe_dir) else m["name"]
    lines.append("#define RECOMP_AUX_STAGE_COUNT %d" % len(staged))
    lines.append("#define RECOMP_AUX_STAGE {%s}" % (", ".join(
        "{%s, %s, %s, %s, %s, %s, %s}" % (c_string(m["name"]), c_string(beside(m)), c_string(st["from"]),
                                          c_string(st["from_sha256"]), c_string(st["prepare"]),
                                          c_hex(m["base"]), c_string(m["sha256"]))
        for m, st in staged) or "{0, 0, 0, 0, 0, 0u, 0}"))
    lines.append("#define RECOMP_REQUIRED_DIRS %s" % c_string_list(cfg["setup"]["required_dirs"]))
    lines.append("#define RECOMP_BUNDLE_EXCLUDE %s" % c_string_list(cfg["bundle"]["exclude"]))
    for key, value in sorted(cfg.get("hooks", {}).items()):
        macro = "RECOMP_HOOK_" + key.upper()
        if isinstance(value, list):
            lines.append("#define %s_COUNT %d" % (macro, len(value)))
            lines.append("#define %s {%s}" % (macro, ", ".join(c_hex(v) for v in value)))
        else:
            lines.append("#define %s %s" % (macro, c_hex(value)))
    for key, entry in sorted(cfg.get("globals", {}).items()):
        macro = "RECOMP_GLOBAL_" + key.upper()
        lines.append("#define %s_ADDR %s" % (macro, c_hex(entry["addr"])))
        for field in ("size", "stride", "count"):
            if field in entry:
                lines.append("#define %s_%s %du" % (macro, field.upper(), entry[field]))
        # Any other number is a layout fact the reader of that global needs (fe_root's offsets): hex, by name.
        for field, value in sorted(entry.items()):
            if field not in ("addr", "size", "stride", "count") and isinstance(value, int):
                lines.append("#define %s_%s %s" % (macro, field.upper(), c_hex(value)))
            # A list of names is a set the reader matches against (fe_root's `skip`: overlay packages).
            elif isinstance(value, list) and all(isinstance(v, str) for v in value):
                lines.append("#define %s_%s %s" % (macro, field.upper(), c_string_list(value)))
    return "\n".join(lines) + "\n"


def render_cmake(cfg):
    game = cfg["game"]
    lines = ["# generated by tools/gen_game_config.py from %s -- do not edit" % cfg["source"]]
    for key, macro in STRINGS[:5]:
        lines.append('set(%s "%s")' % (macro, game[key]))
    lines.append("set(RECOMP_IMAGE_BASE %s)" % c_hex(game["image_base"]))
    lines.append("set(RECOMP_HEAP_BASE %s)" % c_hex(game["heap_base"]))
    lines.append("set(RECOMP_GUEST_SIZE %s)" % c_hex(game["guest_size"]))
    lines.append("set(RECOMP_HEAP_EXTRA_BASE %s)" % c_hex(game["heap_extra_base"]))
    lines.append("set(RECOMP_HEAP_EXTRA_SIZE %s)" % c_hex(game["heap_extra_size"]))
    # The generated sources include this header before they define FN_<addr>,
    # which is how a game replaces one translated function with a native one.
    lines.append('set(RECOMP_OVERRIDE_HEADER "%s")'
                 % (cfg["overrides_header"].as_posix() if cfg.get("overrides_header") else ""))
    lines.append("set(RECOMP_AUX_MODULES %s)" % ";".join(m["key"] for m in cfg["aux_modules"]))
    lines.append("set(RECOMP_STORE_HOOKS %s)" % ("ON" if cfg["translate"].get("store_hooks", True) else "OFF"))
    lines.append("set(RECOMP_LTO %s)" % ("ON" if cfg["translate"].get("lto", False) else "OFF"))
    profile = cfg["translate"].get("pgo_profile", "")
    lines.append('set(RECOMP_PGO_PROFILE "%s")' % ((Path(cfg["dir"]) / profile).resolve().as_posix() if profile else ""))
    lines.append('set(RECOMP_DEVELOPER_GAME_DIR "%s")' % cfg["developer_exe_path"].parent.as_posix())
    lines.append('set(RECOMP_DEVELOPER_EXE "%s")' % cfg["developer_exe_path"].as_posix())
    # [translate] native: C replacements for hot functions, compiled with the
    # translation. The header #defines FN_<addr> to each replacement (see the
    # override note in funcs.h); the sources define them.
    native = cfg["translate"].get("native", {})
    game_dir = Path(cfg["dir"])
    if native.get("header"):
        lines.append('set(RECOMP_NATIVE_HEADER "%s")' % (game_dir / native["header"]).resolve().as_posix())
        sources = [(game_dir / s).resolve().as_posix() for s in native.get("sources", ())]
        lines.append('set(RECOMP_NATIVE_SOURCES "%s")' % ";".join(sources))
        # Libraries the replacements call (static archives or names), linked with the translation.
        libs = [(game_dir / l).resolve().as_posix() if "/" in l else l for l in native.get("libs", ())]
        lines.append('set(RECOMP_NATIVE_LIBS "%s")' % ";".join(libs))
    return "\n".join(lines) + "\n"


def write_if_changed(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.is_file() or path.read_text() != text:
        path.write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game-dir", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--cmake", type=Path, required=True)
    args = parser.parse_args()
    cfg = game_config.load(args.game_dir)
    write_if_changed(args.header, render_header(cfg))
    write_if_changed(args.cmake, render_cmake(cfg))


if __name__ == "__main__":
    main()
